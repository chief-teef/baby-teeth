import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const page=await browser.newPage({viewport:{width:1360,height:960}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
await page.goto('http://localhost:5173');
await page.getByRole('button',{name:'+ Text box',exact:true}).click();
await page.locator('.tiptap').fill('An afternoon worth remembering.');
await page.getByRole('button',{name:'B',exact:true}).click();
await page.keyboard.type(' A bold little ending.');
await page.waitForFunction(()=>document.querySelector('#status').textContent==='Saved on this device');
await page.reload();await page.waitForSelector('.tiptap');
assert.match(await page.locator('.tiptap').textContent(),/afternoon/);
await page.getByRole('button',{name:'Arrange',exact:true}).click();
await page.locator('.object.text').click();
await page.getByRole('spinbutton',{name:'Rotate of selected object'}).fill('12');
await page.getByRole('spinbutton',{name:'Rotate of selected object'}).press('Tab');
assert.match(await page.locator('.object.text').getAttribute('style'),/rotate\(12deg\)/);
await page.getByRole('button',{name:'Undo',exact:true}).click();
assert.match(await page.locator('.object.text').getAttribute('style'),/rotate\(0deg\)/);
await page.getByRole('button',{name:'Draw',exact:true}).click();
const r=await page.locator('#stage').boundingBox();await page.mouse.move(r.x+450,r.y+180);await page.mouse.down();await page.mouse.move(r.x+500,r.y+230,{steps:12});await page.mouse.up();
assert.equal(await page.locator('.object.drawing').count(),1);
await page.getByRole('button',{name:'Open large test entry',exact:true}).click();
assert.equal(await page.locator('.object.photo').count(),20);assert.equal(await page.locator('.object.text').count(),30);
await page.waitForTimeout(600);
await page.getByRole('button',{name:'Reading preview ↗',exact:true}).click();
assert.equal(await page.locator('.reader-entry').count(),2);
const boxes=await page.locator('.reader-canvas').last().locator('.object.text').evaluateAll(els=>els.map(e=>({y:e.offsetTop,h:e.offsetHeight})));
for(let i=1;i<boxes.length;i++)assert.ok(boxes[i].y>=boxes[i-1].y+boxes[i-1].h,'phone text must not overlap');
await page.screenshot({path:'test-results/phone-preview.png',fullPage:false});
await page.getByRole('button',{name:'← Back to editor',exact:true}).click();
await page.setViewportSize({width:1024,height:768});await page.screenshot({path:'test-results/editor-ipad.png',fullPage:false});
await page.waitForFunction(()=>document.querySelector('#status').textContent==='Saved on this device');
await page.reload();await page.waitForSelector('.entry');
await page.getByRole('button',{name:/A bigger little entry/}).click();
assert.equal(await page.locator('.object.photo').count(),20);
assert.equal(await page.locator('.object.text').count(),30);
assert.deepEqual(errors,[]);console.log('PASS: editing, recovery, transform undo, drawing, 20/30 capacity, phone reflow, reload; no browser errors.');
}finally{await browser.close();}
