import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const page=await browser.newPage({viewport:{width:1360,height:960}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const baseUrl=process.argv[2]||'http://localhost:5173/';
try{
await page.goto(baseUrl);
await page.getByRole('button',{name:'+ Text box',exact:true}).click();
await page.locator('.tiptap').fill('An afternoon worth remembering.');
await page.getByRole('button',{name:'Bold',exact:true}).click();
await page.keyboard.type(' A bold little ending.');
await page.waitForFunction(()=>document.querySelector('#status').textContent==='Saved on this device');
await page.reload();await page.waitForSelector('.tiptap');
assert.match(await page.locator('.tiptap').textContent(),/afternoon/);

await page.locator('.object.text').click();
const textObject=page.locator('.object.text');
const beforeMove=await textObject.evaluate(e=>parseFloat(e.style.left));
const grab=await textObject.locator('.grab').boundingBox();
await page.mouse.move(grab.x+grab.width/2,grab.y+grab.height/2);await page.mouse.down();
await page.mouse.move(grab.x+grab.width/2+65,grab.y+grab.height/2+30,{steps:8});await page.mouse.up();
assert.ok(await textObject.evaluate(e=>parseFloat(e.style.left))>beforeMove+40,'Drag label must move text');
const beforeResize=await textObject.evaluate(e=>parseFloat(e.style.width));
const corner=await textObject.locator('.resize').boundingBox();
await page.mouse.move(corner.x+corner.width/2,corner.y+corner.height/2);await page.mouse.down();
await page.mouse.move(corner.x+corner.width/2+55,corner.y+corner.height/2+30,{steps:8});await page.mouse.up();
assert.ok(await textObject.evaluate(e=>parseFloat(e.style.width))>beforeResize+30,'Corner handle must resize text');
await page.getByRole('button',{name:'Properties',exact:true}).click();
await page.getByRole('spinbutton',{name:'Rotate of selected object'}).fill('12');
await page.getByRole('spinbutton',{name:'Rotate of selected object'}).press('Tab');
assert.match(await page.locator('.object.text').getAttribute('style'),/rotate\(12deg\)/);
await page.getByRole('button',{name:'Undo',exact:true}).click();
assert.match(await page.locator('.object.text').getAttribute('style'),/rotate\(0deg\)/);
assert.equal(await page.getByRole('button',{name:'Draw',exact:true}).count(),0);assert.equal(await page.locator('#drawing-surface').count(),0);
await page.getByRole('button',{name:'Account & tools',exact:true}).click();await page.locator('summary').click();
await page.getByRole('button',{name:'Open large test entry',exact:true}).click();
assert.equal(await page.locator('.object.photo').count(),20);assert.equal(await page.locator('.object.text').count(),30);
await page.waitForTimeout(600);
await page.getByRole('button',{name:'Reading preview ↗',exact:true}).click();
await page.locator('.book-scene').waitFor();assert.equal(await page.locator('.book-scene').count(),1);
assert.equal(await page.locator('.notebook-text').count(),30);
await page.screenshot({path:'test-results/phone-preview.png',fullPage:false});
await page.getByRole('button',{name:'← Back to editor',exact:true}).click();
await page.setViewportSize({width:1024,height:768});await page.screenshot({path:'test-results/editor-ipad.png',fullPage:false});
await page.waitForFunction(()=>document.querySelector('#status').textContent==='Saved on this device');
await page.reload();await page.waitForSelector('.entry');
await page.getByRole('button',{name:/A bigger little entry/}).click();
assert.equal(await page.locator('.object.photo').count(),20);
assert.equal(await page.locator('.object.text').count(),30);
assert.deepEqual(errors,[]);console.log('PASS: editing, recovery, transform undo, no pen creation, 20/30 overflow recovery, canonical book preview, reload; no browser errors.');
}finally{await browser.close();}
